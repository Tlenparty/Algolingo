package com.tlenparty.algolingo.lesson

import java.io.ByteArrayOutputStream
import java.io.File
import java.io.PrintStream
import java.net.URLClassLoader
import java.nio.file.Files
import java.util.concurrent.Executors
import java.util.concurrent.TimeUnit
import java.util.concurrent.TimeoutException
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import org.jetbrains.kotlin.cli.common.ExitCode
import org.jetbrains.kotlin.cli.jvm.K2JVMCompiler
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue
import kotlin.test.fail
import com.tlenparty.algolingo.lesson.domain.Chip
import com.tlenparty.algolingo.lesson.domain.Exercise
import com.tlenparty.algolingo.lesson.domain.Hole
import com.tlenparty.algolingo.lesson.domain.Lesson
import com.tlenparty.algolingo.lesson.domain.Solution
import com.tlenparty.algolingo.progress.domain.Catalog

/**
 * Proves every wrong-chip claim (JVM only): each program from wrong_variants.json (generated by
 * tools/gen_content.py) is compiled with the embedded compiler and run; `V.kinds()` reports which
 * examples broke and how. Observed kinds: compile | wrong | crash | hang; empty = runs clean.
 * Each lesson also has a "control" entry (its reference through the same harness) that must run clean,
 * so a broken harness/classpath cannot pass off as proven [compile] claims.
 * All mismatches go into one message and build/reports/wrong-chips.txt (with compiler diagnostics).
 */
class WrongChipsTest {
    @Serializable
    data class Claim(val bullet: String, val scope: String, val tags: List<String>)

    @Serializable
    data class Entry(
        val id: String,
        val ids: List<String>,
        val lesson: String,
        val label: String,
        val claims: List<Claim>,
        val source: String,
        val control: Boolean = false,
    )

    /** kinds seen; log = compiler diagnostics when kinds == {compile}. */
    data class Obs(val kinds: Set<String>, val log: String = "")

    private val cp = listOf(loc(Unit::class.java), loc(Class.forName("kotlin.test.AssertionsKt")))
        .joinToString(File.pathSeparator)

    private fun loc(c: Class<*>) = File(c.protectionDomain.codeSource.location.toURI()).path

    private fun observe(source: String, timeoutMs: Long = 20_000): Obs {
        val dir = Files.createTempDirectory("wv").toFile()
        try {
            val src = File(dir, "V.kt").also { it.writeText(source) }
            val out = File(dir, "out")
            val diag = ByteArrayOutputStream()
            val code = K2JVMCompiler().exec(
                PrintStream(diag), "-no-stdlib", "-no-reflect", "-nowarn",
                "-cp", cp, "-d", out.path, src.path,
            )
            if (code != ExitCode.OK) {
                val log = diag.toString().lines().filter { "error:" in it }.take(3)
                    .joinToString(" | ") { it.substringAfter("V.kt:").trim() }
                return Obs(setOf("compile"), log)
            }
            URLClassLoader(arrayOf(out.toURI().toURL()), javaClass.classLoader).use { cl ->
                val c = cl.loadClass("V")
                // D-05 safety net over tick(): a loop tick() does not cover (recursion, lambdas, ranges)
                // must not hang the whole run; the stuck daemon thread is abandoned
                val ex = Executors.newSingleThreadExecutor { r -> Thread(r, "wrong-variant").apply { isDaemon = true } }
                try {
                    val kinds = ex.submit<String> { c.getMethod("kinds").invoke(c.getField("INSTANCE").get(null)) as String }
                        .get(timeoutMs, TimeUnit.MILLISECONDS)
                    return Obs(kinds.split(',').filter { it.isNotEmpty() }.toSet())
                } catch (e: TimeoutException) {
                    return Obs(setOf(UNTRACKED_HANG), "no result in ${timeoutMs}ms")
                } finally {
                    ex.shutdownNow()
                }
            }
        } finally {
            dir.deleteRecursively()
        }
    }

    /** Pure check, so the guards against a vacuous pass are themselves tested (noVacuousPass). */
    private fun findings(entries: List<Entry>, observed: Map<String, Obs>, lessons: List<Lesson>): List<String> {
        val findings = mutableListOf<String>()
        // coverage: exactly one program per (hole, chip not correct for it) of the shipped lessons, plus a
        // control per lesson; an empty or truncated wrong_variants.json cannot pass as "0 findings"
        if (lessons.isEmpty()) findings += "no lessons in the catalog"
        val expected = lessons.flatMap { l ->
            l.exercises.flatMap { ex ->
                ex.holes.flatMapIndexed { i, h ->
                    val correct = h.ok.toSet() + h.acceptable.map { it.text }
                    ex.bank.map { it.text }.filter { it !in correct }.map { "${ex.id}.h${i + 1}:$it" }
                }
            }
        }.toSet()
        val got = entries.filter { !it.control }.flatMap { it.ids }.toSet()
        (expected - got).let { if (it.isNotEmpty()) findings += "${it.size} wrong pairs have no program: ${it.sorted().take(10)}" }
        (got - expected).let { if (it.isNotEmpty()) findings += "${it.size} programs match no shipped pair: ${it.sorted().take(10)}" }
        val controlled = entries.filter { it.control }.map { it.lesson }.toSet()
        lessons.filter { it.id !in controlled }.forEach { findings += "lesson ${it.id} has no control program" }
        for (e in entries.filter { it.control }) {
            val o = observed.getValue(e.id)
            if (o.kinds.isNotEmpty()) findings +=
                "CONTROL ${e.id} observed ${o.kinds.sorted()} ${o.log}: harness broken for ${e.lesson}, its claims prove nothing"
        }
        val programs = entries.filter { !it.control }
        for (e in programs) {
            val o = observed.getValue(e.id).kinds
            if (o.isEmpty()) findings += "${e.id} runs clean (false wrong?) [${e.label}]"
            if (UNTRACKED_HANG in o) findings += "${e.id} hangs past tick(): cover the loop in instrument() or ban it (G11)"
            for (c in e.claims.filter { it.scope == "hole" }) {
                val missing = c.tags - o
                if (missing.isNotEmpty()) findings += "${e.id} ${c.bullet}: expected ${c.tags} observed ${o.sorted()} (missing $missing)"
            }
        }
        // chip scope: the reason holds for the chip in any hole of the exercise, so tags must be in the union
        val groups = programs.flatMap { e -> e.claims.filter { it.scope == "chip" }.map { it to e } }
            .groupBy({ it.first.bullet }, { it.second })
        for ((bullet, group) in groups) {
            val tags = programs.flatMap { it.claims }.first { it.bullet == bullet && it.scope == "chip" }.tags
            val union = group.flatMap { observed.getValue(it.id).kinds }.toSet()
            val missing = tags - union
            if (missing.isNotEmpty()) findings +=
                "${group.joinToString("+") { it.id }} $bullet: expected $tags observed ${union.sorted()} (missing $missing)"
        }
        return findings
    }

    @Test
    fun everyWrongChipBreaksAsTagged() {
        val entries = Json { ignoreUnknownKeys = true }
            .decodeFromString<List<Entry>>(File("src/androidHostTest/resources/wrong_variants.json").readText())
        val dir = File("src/commonMain/composeResources/files/content")
        val json = Json { ignoreUnknownKeys = true }
        val lessons = json.decodeFromString<Catalog>(File(dir, "index.json").readText()).lessons
            .map { json.decodeFromString<Lesson>(File(dir, "lessons/${it.id}.json").readText()) }
        val observed = entries.associate { it.id to observe(it.source) }
        val findings = findings(entries, observed, lessons)

        val report = File("build/reports/wrong-chips.txt")
        report.parentFile.mkdirs()
        report.writeText(
            (listOf("# ${entries.size} programs, ${findings.size} findings") +
                findings + entries.map { e ->
                    val o = observed.getValue(e.id)
                    "observed ${e.id}: ${o.kinds.sorted()}" + if (o.log.isEmpty()) "" else "  // ${o.log}"
                })
                .joinToString("\n", postfix = "\n"),
        )
        if (findings.isNotEmpty()) fail("${findings.size} wrong-chip mismatches (see ${report.path}):\n" + findings.joinToString("\n"))
    }

    @Test
    fun noVacuousPass() {
        val control = Entry("l9.control", listOf("l9.control"), "l9", "reference (control)", emptyList(), "", control = true)
        val wrong = Entry("l9.e1.h1:x", listOf("l9.e1.h1:x"), "l9", "x", listOf(Claim("b", "hole", listOf("compile"))), "")
        val lesson = Lesson(
            id = "l9", title = "", statement = "", solution = Solution("", "", ""),
            exercises = listOf(Exercise("l9.e1", listOf("", ""), listOf(Hole(listOf("a"))), listOf(Chip("a"), Chip("x")))),
        )
        val ok = mapOf(control.id to Obs(emptySet()), wrong.id to Obs(setOf("compile")))
        assertEquals(emptyList(), findings(listOf(control, wrong), ok, listOf(lesson)))
        // a lesson whose harness does not compile must not turn its [compile] claim green
        val broken = findings(listOf(control, wrong), ok + (control.id to Obs(setOf("compile"), "boom")), listOf(lesson))
        assertTrue(broken.any { it.startsWith("CONTROL l9.control") }, broken.toString())
        // empty / truncated input or an empty catalog is a finding, not "0 findings"
        assertTrue(findings(emptyList(), emptyMap(), listOf(lesson)).size == 2)
        assertTrue(findings(listOf(control), ok, listOf(lesson)).any { "have no program" in it })
        assertTrue(findings(emptyList(), emptyMap(), emptyList()).isNotEmpty())
        // a hang caught only by the safety timeout is reported even when the claim allows any kind
        assertTrue(findings(listOf(control, wrong), ok + (wrong.id to Obs(setOf("compile", UNTRACKED_HANG))), listOf(lesson))
            .any { "hangs past tick()" in it })
    }

    @Test
    fun classifierSanity() {
        val clean = """
            object V {
                fun kinds(): String = ""
            }
        """.trimIndent()
        assertEquals(emptySet(), observe(clean).kinds)
        // uses kotlin.test so a broken classpath shows up here, not as 248 "compile" verdicts
        val wrong = """
            import kotlin.test.*
            object V {
                fun kinds(): String = try { assertEquals(1, 2); "" } catch (e: AssertionError) { "wrong" }
            }
        """.trimIndent()
        assertEquals(setOf("wrong"), observe(wrong).kinds)
        val bad = observe("object V { fun kinds(): String = 1 }")
        assertEquals(setOf("compile"), bad.kinds)
        assertTrue(bad.log.isNotEmpty(), "compiler diagnostics are kept")
        // a hang tick() does not see ends as a finding instead of blocking the test run
        val stuck = observe("object V { fun kinds(): String { Thread.sleep(60_000); return \"\" } }", timeoutMs = 500)
        assertEquals(setOf(UNTRACKED_HANG), stuck.kinds)
    }

    private companion object {
        const val UNTRACKED_HANG = "hang-untracked"
    }
}
